package ut1IntroProg;

public class ejercicio_while {
	 public static void main(String[] args) {

	        int contador = 10;

	        while (contador > 0) {
	            System.out.println("Cuenta atrás: " + contador);
	            contador = contador - 3;
	        }

	        System.out.println("Fin del bucle");
	    }
}
